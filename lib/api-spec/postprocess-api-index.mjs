import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const directory = path.dirname(fileURLToPath(import.meta.url));
const clientSource = path.resolve(directory, "../api-client-react/src");
const generatedApiPath = path.join(clientSource, "generated/api.ts");
const generatedSchemasPath = path.join(clientSource, "generated/api.schemas.ts");
for (const generatedPath of [generatedApiPath, generatedSchemasPath]) {
  const source = await readFile(generatedPath, "utf8");
  await writeFile(generatedPath, `${source.trimEnd()}\n`, "utf8");
}
const generatedApi = await readFile(generatedApiPath, "utf8");
const values = new Set();
const types = new Set();

for (const match of generatedApi.matchAll(/^export\s+(const|function|class|enum|type|interface)\s+(\w+)/gm)) {
  const [, kind, name] = match;
  if (kind === "type" || kind === "interface") types.add(name);
  else values.add(name);
}

const sortedValues = [...values].sort();
const sortedTypes = [...types].sort();
const indexSource = [
  "// Generated by postprocess-api-index.mjs after Orval. Do not edit manually.",
  `export { ${sortedValues.join(", ")} } from "./generated/api";`,
  `export type { ${sortedTypes.join(", ")} } from "./generated/api";`,
  'export * from "./generated/api.schemas";',
  'export { setBaseUrl, setAuthTokenGetter } from "./custom-fetch";',
  'export type { AuthTokenGetter } from "./custom-fetch";',
  "",
].join("\n");

await writeFile(path.join(clientSource, "index.ts"), indexSource, "utf8");