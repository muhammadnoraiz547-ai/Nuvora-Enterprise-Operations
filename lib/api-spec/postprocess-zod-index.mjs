import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const directory = path.dirname(fileURLToPath(import.meta.url));
const zodSource = path.resolve(directory, "../api-zod/src");
const apiPath = path.join(zodSource, "generated/api.ts");
const typesDirectory = path.join(zodSource, "generated/types");
const typeIndexPath = path.join(typesDirectory, "index.ts");
const generatedApiSource = await readFile(apiPath, "utf8");
await writeFile(apiPath, `${generatedApiSource.trimEnd()}\n`, "utf8");

const apiSource = await readFile(apiPath, "utf8");
const typeIndex = await readFile(typeIndexPath, "utf8");
const apiNames = new Set(
  [...apiSource.matchAll(/^export\s+(?:const|type|interface|enum)\s+(\w+)/gm)].map((match) => match[1]),
);
const exportsByModule = [];

for (const [, moduleName] of typeIndex.matchAll(/^export\s+\*\s+from\s+['"]\.\/([^'"]+)['"];?/gm)) {
  const moduleSource = await readFile(path.join(typesDirectory, `${moduleName}.ts`), "utf8");
  const typeNames = new Set();
  const valueNames = new Set();

  for (const match of moduleSource.matchAll(/^export\s+(type|interface|const|enum)\s+(\w+)/gm)) {
    const [, kind, name] = match;
    if (kind === "const" || kind === "enum") valueNames.add(name);
    else if (!apiNames.has(name)) typeNames.add(name);
  }

  const exports = [];
  for (const valueName of valueNames) typeNames.delete(valueName);
  if (typeNames.size) exports.push(`export type { ${[...typeNames].join(", ")} } from "./generated/types/${moduleName}";`);
  const distinctValues = [...valueNames].filter((name) => !apiNames.has(name));
  if (distinctValues.length) exports.push(`export { ${distinctValues.join(", ")} } from "./generated/types/${moduleName}";`);
  exportsByModule.push(...exports);
}

const output = [
  "// Generated by postprocess-zod-index.mjs after Orval. Do not edit manually.",
  'export * from "./generated/api";',
  'export { HealthCheckApiHealthzGetResponse as HealthCheckResponse } from "./generated/api";',
  ...exportsByModule,
  "",
].join("\n");

await writeFile(path.join(zodSource, "index.ts"), output, "utf8");